function parse(src) {
  const m = /^(\d):(.*)$/.exec(src);
  const top = m ? Number(m[1]) : 0;
  const rows = (m ? m[2] : src).split('/').filter((r) => r.length);
  const out = new Array(GLYPH_H).fill(0);
  rows.forEach((row, i) => {
    let bits = 0;
    for (let x = 0; x < GLYPH_W; x++) if (row[x] === '#') bits |= 1 << (GLYPH_W - 1 - x);
    if (top + i < GLYPH_H) out[top + i] = bits;
  });
  return out;
}

const GLYPHS = new Map(Object.entries(SRC).map(([ch, src]) => [ch, parse(src)]));
const BLANK = new Array(GLYPH_H).fill(0);

/** Row bitmasks (GLYPH_H rows, bit GLYPH_W-1 is the left pixel) for one character. Unknown characters are blank. */
export function glyph(ch) {
  return GLYPHS.get(ch) || BLANK;
}
