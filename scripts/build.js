// Assemble dist/ from public/, src/ and data/. No bundler: the browser loads ES modules directly.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist');

fs.rmSync(DIST, { recursive: true, force: true });
fs.mkdirSync(DIST, { recursive: true });
fs.cpSync(path.join(ROOT, 'public'), DIST, { recursive: true });
fs.cpSync(path.join(ROOT, 'src'), path.join(DIST, 'src'), { recursive: true });
fs.cpSync(path.join(ROOT, 'data'), path.join(DIST, 'data'), { recursive: true });
fs.writeFileSync(path.join(DIST, '.nojekyll'), '');

// Embedded snapshot: used when data/*.json cannot be fetched (for example opened from a odd host).
const snapshot = {};
for (const f of fs.readdirSync(path.join(ROOT, 'data')).filter((n) => n.endsWith('.json'))) {
  snapshot[f.replace(/\.json$/, '')] = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', f), 'utf8'));
}
fs.writeFileSync(
  path.join(DIST, 'src', 'data', 'snapshot.js'),
  '// Generated by scripts/build.js. Do not edit.\nexport default ' + JSON.stringify(snapshot) + ';\n',
);
console.log('built dist/ (' + fs.readdirSync(DIST).join(', ') + ')');
